WHERE ROWNUM < 6;

-- RUN AS: DB_VPD
-- Disable policy
BEGIN
    DBMS_RLS.ENABLE_POLICY(
        OBJECT_SCHEMA => 'DB_VPD',
        OBJECT_NAME => 'CUSTOMERS',
        POLICY_NAME => 'DB_VPD_ROLE_SECURITY_POLICY',
        ENABLE => FALSE
    );
END;