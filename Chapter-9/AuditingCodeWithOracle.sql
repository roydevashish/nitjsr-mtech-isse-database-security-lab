-- RUN AS: DB_AUDIT
CREATE TABLE DB_AUDIT.APP_AUDIT_SQLS (
    TABLE_NAME VARCHAR2(30) NOT NULL,
    SQL_STATEMENT VARCHAR2(4000) NOT NULL,
    SQL_TYPE VARCHAR2(10) NOT NULL,
    CTL_INS_DTTM TIMESTAMP,
    CTL_INS_USER VARCHAR2(30),
    CTL_OPS_USER VARCHAR2(30),
    CTL_IP_ADDR VARCHAR2(255)
);

CREATE TABLE DB_AUDIT.CUSTOMERS (
    ID NUMBER,
    NAME VARCHAR2(10),
    CREDIT_LIMIT NUMBER
);

