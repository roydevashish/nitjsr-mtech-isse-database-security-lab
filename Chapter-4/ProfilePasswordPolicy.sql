GRANT CREATE SESSION TO SAFYOUNI;

-- List all the users
SELECT USERNAME, PROFILE
FROM DBA_USERS
ORDER BY CREATED DESC
/

-- Assign new profile: PROFILE_PASSWORD_POLICY to user: SAFYOUNI using ALTER USER
ALTER USER SAFYOUNI
